"""Post-processing DAG deduplication: remove redundant nodes whose formula already
appears at a strictly shallower depth.

Unlike BFS-time pruning (which causes cascading recall loss), this runs AFTER the full
DAG is built so all intermediate fragments are preserved. Only nodes whose formula is
already covered at a shallower depth are candidates for removal.

Two strategies are tested side-by-side:
  - leaf_only: remove only max-depth nodes (true leaves) with redundant formula
  - all_depths: remove any node at depth d if its formula exists at depth < d
    (safe because children were already generated by the time we prune)

Reports: nodes/edges before vs after, matched-formula recall (should stay 100%).

Usage:
    python scripts/debug/debug_dag_postproc_dedup.py \
        --tar data/frag/nist20_ma_mi_d3_h4_isoFalse_smpFalse.tar \
        --n_sample 500 --seed 42

    python scripts/debug/debug_dag_postproc_dedup.py \
        --tar data/frag/nist20_ma_mi_d4_h4_isoFalse_smpFalse.tar \
        --n_sample 500 --seed 42
"""

import argparse
import bz2
import pickle
import random
import sys
import tarfile
from collections import defaultdict

import numpy as np

sys.path.insert(0, "src")
from fragnnet.utils.frag_utils import ELEMENT_TO_IDX, get_node_feats


def formula_arr_to_str(arr) -> str:
    parts = []
    for elem, idx in sorted(ELEMENT_TO_IDX.items(), key=lambda x: x[1]):
        if elem == "H":
            continue
        if arr[idx] > 0:
            parts.append(f"{elem}{int(arr[idx])}")
    return "".join(parts)


def get_remove_set_all_depths(node_depth, node_fstr, n_nodes) -> set[int]:
    """Remove any node at depth d if its base formula exists at a shallower depth."""
    formula_min_depth: dict[str, int] = {}
    for ni in range(n_nodes):
        d, f = node_depth[ni], node_fstr[ni]
        if f not in formula_min_depth or d < formula_min_depth[f]:
            formula_min_depth[f] = d
    return {ni for ni in range(n_nodes) if formula_min_depth[node_fstr[ni]] < node_depth[ni]}


def get_remove_set_hybrid(node_depth, node_fstr, h_formulae_idx, n_nodes) -> set[int]:
    """Remove a node at depth d only if BOTH:
      1. Its base formula exists at a strictly shallower depth (depth > min_depth), AND
      2. All its h-formula indices are already covered by kept nodes at shallower depths.

    Never removes min-depth nodes (preserves core structure).
    Never loses h-indices (safer than all_depths).
    Less aggressive than h_coverage (no same-depth dedup).
    """
    formula_to_nodes: dict[str, list[tuple[int, int]]] = defaultdict(list)
    for ni in range(n_nodes):
        formula_to_nodes[node_fstr[ni]].append((node_depth[ni], ni))

    remove_set: set[int] = set()
    for node_list in formula_to_nodes.values():
        if len(node_list) == 1:
            continue
        node_list.sort(key=lambda x: x[0])  # shallowest first
        min_depth = node_list[0][0]
        covered_h: set[int] = set()  # h-indices from kept nodes seen so far

        for depth, ni in node_list:
            node_h = {v.item() for v in h_formulae_idx[ni] if v.item() > 0}
            if depth == min_depth:
                covered_h |= node_h  # always keep min-depth nodes
            elif node_h <= covered_h:
                remove_set.add(ni)   # deeper + h-indices fully covered → remove
            else:
                covered_h |= node_h  # deeper but adds new h-indices → keep
    return remove_set


def get_remove_set_h_coverage(node_depth, node_fstr, h_formulae_idx, n_nodes) -> set[int]:
    """Remove a node only if all its h-formula indices are already covered by a
    shallower node with the same base formula.

    Processes nodes shallowest-first so minimum-depth nodes are always kept first.
    Guarantees 0% h-formula index loss.
    """
    formula_to_nodes: dict[str, list[tuple[int, int]]] = defaultdict(list)
    for ni in range(n_nodes):
        formula_to_nodes[node_fstr[ni]].append((node_depth[ni], ni))

    remove_set: set[int] = set()
    for node_list in formula_to_nodes.values():
        if len(node_list) == 1:
            continue
        node_list.sort(key=lambda x: x[0])  # shallowest first
        covered_h: set[int] = set()
        for _depth, ni in node_list:
            node_h = {v.item() for v in h_formulae_idx[ni] if v.item() > 0}
            if node_h <= covered_h:
                remove_set.add(ni)
            else:
                covered_h |= node_h
    return remove_set


def analyze_dag(dag: dict) -> dict | None:
    """Apply three post-proc strategies and measure size + recall impact.

    Strategies:
      - leaf_only:    remove max-depth nodes whose base formula exists at shallower depth
      - all_depths:   remove any node whose base formula exists at shallower depth
      - h_coverage:   remove a node only when all its h-formula indices are already
                      covered by a shallower node (same base formula)

    Returns a stats dict, or None if the DAG has no matched formulas.
    """
    g = dag["dag"]
    x = g.x
    edge_index = g.edge_index
    node_feat_idxs = g.node_feat_idxs[0]
    nmd = dag["nodes_min_depth"]
    fpp = dag["formula_peak_probs"]  # [n_formulae, n_spectra]

    base_formula = get_node_feats(x, node_feat_idxs, "base_formula")  # [n_nodes, 12]
    h_formulae_idx = get_node_feats(x, node_feat_idxs, "h_formulae_idx")  # [n_nodes, 9]
    n_nodes = x.shape[0]
    n_edges = edge_index.shape[1]

    node_depth = [int(nmd[ni]) if not hasattr(nmd[ni], "item") else nmd[ni].item() for ni in range(n_nodes)]
    node_fstr = [formula_arr_to_str(base_formula[ni].numpy()) for ni in range(n_nodes)]
    max_depth = max(node_depth)

    # Matched h-formula indices (fidx with fpp > 0)
    matched_fidxs: set[int] = {
        fidx for fidx in range(1, fpp.shape[0]) if fpp[fidx].sum() > 0
    }
    if not matched_fidxs:
        return None

    def count_removed(remove_nodes: set) -> tuple[int, int, int]:
        """Count removed nodes/edges and lost matched h-formula indices."""
        rm_edges = sum(1 for ei in range(n_edges) if edge_index[1, ei].item() in remove_nodes)
        # Which matched fidxs are still carried by at least one kept node?
        kept_fidxs: set[int] = set()
        for ni in range(n_nodes):
            if ni in remove_nodes:
                continue
            for v in h_formulae_idx[ni]:
                fidx = v.item()
                if fidx > 0:
                    kept_fidxs.add(fidx)
        lost_h = len(matched_fidxs - kept_fidxs)
        return len(remove_nodes), rm_edges, lost_h

    # Strategy 1: leaf_only
    formula_min_depth: dict[str, int] = {}
    for ni in range(n_nodes):
        d, f = node_depth[ni], node_fstr[ni]
        if f not in formula_min_depth or d < formula_min_depth[f]:
            formula_min_depth[f] = d

    leaf_remove = {
        ni for ni in range(n_nodes)
        if node_depth[ni] == max_depth and formula_min_depth[node_fstr[ni]] < max_depth
    }
    ln, le, l_lost = count_removed(leaf_remove)

    # Strategy 2: all_depths
    all_remove = get_remove_set_all_depths(node_depth, node_fstr, n_nodes)
    an, ae, a_lost = count_removed(all_remove)

    # Strategy 3: hybrid (depth-gated + h-index coverage)
    hyb_remove = get_remove_set_hybrid(node_depth, node_fstr, h_formulae_idx, n_nodes)
    hybn, hybe, hyb_lost = count_removed(hyb_remove)

    # Strategy 4: h_coverage
    hc_remove = get_remove_set_h_coverage(node_depth, node_fstr, h_formulae_idx, n_nodes)
    hn, he, h_lost = count_removed(hc_remove)

    return {
        "n_nodes": n_nodes,
        "n_edges": n_edges,
        "n_matched_h": len(matched_fidxs),
        # leaf_only
        "leaf_rm_nodes": ln, "leaf_rm_edges": le, "leaf_lost_h": l_lost,
        # all_depths
        "all_rm_nodes": an, "all_rm_edges": ae, "all_lost_h": a_lost,
        # hybrid
        "hyb_rm_nodes": hybn, "hyb_rm_edges": hybe, "hyb_lost_h": hyb_lost,
        # h_coverage
        "hc_rm_nodes": hn, "hc_rm_edges": he, "hc_lost_h": h_lost,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tar", required=True)
    parser.add_argument("--n_sample", type=int, default=500)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    print(f"Scanning {args.tar} ...")
    with tarfile.open(args.tar, "r") as tf:
        members = [m for m in tf.getmembers() if m.name.endswith(".pkl.bz2") and "/dags/" in m.name]
    print(f"  Total DAG files: {len(members):,}")

    random.seed(args.seed)
    sample = random.sample(members, min(args.n_sample, len(members)))
    print(f"  Sampling {len(sample):,} molecules ...\n")

    totals: dict[str, int] = defaultdict(int)
    n_analyzed = 0

    with tarfile.open(args.tar, "r") as tf:
        for i, member in enumerate(sample):
            if i % 100 == 0:
                print(f"  {i}/{len(sample)} ...")
            f = tf.extractfile(member)
            if f is None:
                continue
            dag = pickle.loads(bz2.decompress(f.read()))
            if dag["reached_depth"] < 1:
                continue
            result = analyze_dag(dag)
            if result is None:
                continue
            for k, v in result.items():
                totals[k] += v
            n_analyzed += 1

    if n_analyzed == 0:
        print("No molecules analyzed.")
        return

    nn = totals["n_nodes"]
    ne = totals["n_edges"]
    nm = totals["n_matched_h"]

    def pct(removed, total):
        return f"{100*removed/total:.1f}%" if total else "N/A"

    def recall(lost, total):
        return f"{100*(total-lost)/total:.2f}%" if total else "N/A"

    print(f"\nAnalyzed {n_analyzed:,} molecules")
    print(f"\n{'='*96}")
    print(f"{'':32s} {'baseline':>10}  {'leaf_only':>10}  {'all_depths':>10}  {'hybrid':>10}  {'h_coverage':>10}")
    print(f"{'-'*96}")
    print(f"  {'nodes':<30} {nn:>10,}  "
          f"{nn-totals['leaf_rm_nodes']:>10,}  "
          f"{nn-totals['all_rm_nodes']:>10,}  "
          f"{nn-totals['hyb_rm_nodes']:>10,}  "
          f"{nn-totals['hc_rm_nodes']:>10,}")
    print(f"  {'edges':<30} {ne:>10,}  "
          f"{ne-totals['leaf_rm_edges']:>10,}  "
          f"{ne-totals['all_rm_edges']:>10,}  "
          f"{ne-totals['hyb_rm_edges']:>10,}  "
          f"{ne-totals['hc_rm_edges']:>10,}")
    print(f"  {'node reduction':<30} {'—':>10}  "
          f"{pct(totals['leaf_rm_nodes'],nn):>10}  "
          f"{pct(totals['all_rm_nodes'],nn):>10}  "
          f"{pct(totals['hyb_rm_nodes'],nn):>10}  "
          f"{pct(totals['hc_rm_nodes'],nn):>10}")
    print(f"  {'edge reduction':<30} {'—':>10}  "
          f"{pct(totals['leaf_rm_edges'],ne):>10}  "
          f"{pct(totals['all_rm_edges'],ne):>10}  "
          f"{pct(totals['hyb_rm_edges'],ne):>10}  "
          f"{pct(totals['hc_rm_edges'],ne):>10}")
    print(f"\n  {'matched h-formula recall':<30} {'100.00%':>10}  "
          f"{recall(totals['leaf_lost_h'],nm):>10}  "
          f"{recall(totals['all_lost_h'],nm):>10}  "
          f"{recall(totals['hyb_lost_h'],nm):>10}  "
          f"{recall(totals['hc_lost_h'],nm):>10}")


if __name__ == "__main__":
    main()
